async page => {
  const state = page.__picpilotMocks
  if (!page.url().endsWith('/setup')) throw new Error('Deep link did not route to setup')
  if (state.requests.some(r => !['/api/public/config', '/api/setup/status'].includes(r.path))) throw new Error('A workflow mounted before setup')
  await page.getByRole('textbox', { name: 'Owner email', exact: true }).fill('owner@example.test')
  await page.getByRole('textbox', { name: 'Password', exact: true }).fill('short')
  await page.getByRole('textbox', { name: 'Confirm password', exact: true }).fill('short')
  await page.getByRole('textbox', { name: 'Setup token', exact: true }).fill('mock-setup-token')
  await page.getByRole('button', { name: 'Create owner', exact: true }).click()
  await page.getByText('Use 12–72 UTF-8 bytes. Non-ASCII characters may use multiple bytes.', { exact: true }).waitFor()
  if (state.requests.some(r => r.path === '/api/setup')) throw new Error('Invalid password was sent')
  await page.getByRole('textbox', { name: 'Password', exact: true }).fill('mock-valid-password')
  await page.getByRole('textbox', { name: 'Confirm password', exact: true }).fill('mock-other-password')
  await page.getByRole('button', { name: 'Create owner', exact: true }).click()
  await page.getByText('Passwords do not match', { exact: true }).waitFor()
  await page.screenshot({ path: 'output/playwright/setup-validation-desktop.png', fullPage: true })
  await page.getByRole('textbox', { name: 'Confirm password', exact: true }).fill('mock-valid-password')
  await page.getByRole('button', { name: 'Create owner', exact: true }).click()
  await page.waitForURL('**/login')
  const submitted = state.requests.filter(r => r.path === '/api/setup')
  if (submitted.length !== 1) throw new Error('Setup should be submitted exactly once')
  const body = JSON.parse(submitted[0].body)
  if (Object.keys(body).sort().join() !== 'confirm_password,email,password,setup_token') throw new Error('Wrong setup body')
  if (await page.evaluate(() => JSON.stringify(localStorage).includes('mock-valid-password') || JSON.stringify(localStorage).includes('mock-setup-token'))) throw new Error('Setup credentials persisted')
  await page.goto('http://127.0.0.1:13280/providers')
}
