async page => {
  const state = page.__picpilotMocks
  await page.getByRole('button', { name: 'Edit provider My text provider', exact: true }).click()
  const key = page.getByRole('textbox', { name: /^API key/ })
  if (await key.inputValue() !== '' || await key.getAttribute('type') !== 'password') throw new Error('Key is not blank and masked')
  await page.getByRole('textbox', { name: 'Model name', exact: true }).fill('my-custom-text-model')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByText('my-custom-text-model', { exact: true }).waitFor()
  const saved = state.requests.filter(r => r.path === '/api/me/providers/mock-text' && r.method === 'PUT').at(-1)
  if ('api_key' in JSON.parse(saved.body)) throw new Error('Blank key was not preserved')
  await page.getByRole('button', { name: 'Validate configuration My text provider', exact: true }).click()
  await page.getByText('Configuration validated. This does not verify connectivity or model availability; no generation request was made.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Add provider', exact: true }).click()
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('My image provider')
  await page.getByRole('combobox', { name: 'Capability', exact: true }).selectOption('image')
  await page.getByRole('combobox', { name: 'Protocol', exact: true }).selectOption('openai_images_edits')
  await page.getByRole('textbox', { name: 'Base URL', exact: true }).fill('https://user:password@provider.example.test')
  await page.getByRole('textbox', { name: 'Model name', exact: true }).fill('vendor/manual-image-model')
  await page.getByRole('textbox', { name: /^API key/ }).fill('mock-api-key-never-persist')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByText('Enter an HTTP(S) base URL without credentials, query parameters or fragments', { exact: true }).waitFor()
  await page.getByRole('textbox', { name: 'Base URL', exact: true }).fill('https://provider.example.test/custom/v1')
  state.failSave = true
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByText(/This mock adapter is not implemented/).waitFor()
  await page.screenshot({ path: 'output/playwright/provider-error-desktop.png', fullPage: true })
  state.failSave = false
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByRole('heading', { name: 'My image provider', exact: true }).waitFor()
  if (await page.evaluate(() => JSON.stringify(localStorage).includes('mock-api-key-never-persist') || JSON.stringify(sessionStorage).includes('mock-api-key-never-persist'))) throw new Error('Provider key persisted in browser storage')
  await page.getByRole('checkbox', { name: 'Enabled My text provider', exact: true }).uncheck()
  await page.getByRole('button', { name: 'Add provider', exact: true }).click()
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('My video provider')
  await page.getByRole('combobox', { name: 'Capability', exact: true }).selectOption('video')
  await page.getByRole('combobox', { name: 'Protocol', exact: true }).selectOption('hfsy_video')
  await page.locator('option[value="pull_worker"]:disabled').waitFor({ state: 'attached' })
  await page.getByRole('textbox', { name: 'Base URL', exact: true }).fill('https://video.example.test')
  await page.getByRole('textbox', { name: 'Model name', exact: true }).fill('manually-configured-video-model')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'output/playwright/providers-mobile.png', fullPage: true })
  if (await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)) throw new Error('Provider form overflows mobile width')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByRole('heading', { name: 'My video provider', exact: true }).waitFor()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: 'output/playwright/providers-desktop.png', fullPage: true })
  if (state.requests.some(r => /^\/api\/(billing|admin|benefits|messages)(\/|$)/.test(r.path))) throw new Error('Personal edition called a platform endpoint')
  if (state.external.length) throw new Error('Unexpected external request')
  await page.getByRole('button', { name: 'Delete provider My image provider', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm', exact: true }).click()
  await page.getByText('Provider deleted', { exact: true }).waitFor()
  if (state.providers.some(p => p.name === 'My image provider')) throw new Error('Provider deletion did not update the mock')
  await page.goto('http://127.0.0.1:13280/credits')
  await page.waitForURL('**/providers')
  await page.goto('http://127.0.0.1:13280/video-create')
  await page.getByRole('heading', { name: '商品视频', exact: true }).waitFor()
  if (state.requests.some(r => /^\/api\/(billing|admin|benefits|messages)(\/|$)/.test(r.path))) throw new Error('Personal workflow called a platform endpoint')
  await page.goto('http://127.0.0.1:13281/users')
}
