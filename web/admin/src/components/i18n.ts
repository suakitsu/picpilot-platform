function currentLanguage() {
  if (typeof window === 'undefined') return 'zh-CN'
  return localStorage.getItem('openimage-language') || 'zh-CN'
}

function useLanguageValue() {
  const [lang, setLang] = useState('zh-CN')

  useEffect(() => {
    const sync = () => setLang(currentLanguage())
    sync()
    window.addEventListener('openimage:language-updated', sync)
    window.addEventListener('storage', sync)
    return () => {
      window.removeEventListener('openimage:language-updated', sync)
      window.removeEventListener('storage', sync)
    }
  }, [])

  return lang
}

export function useLocale() {
  return useLanguageValue()
}

export function useI18n() {
  const lang = useLanguageValue()
  return useCallback((key: string) => editionMessages[lang]?.[key] || dict[lang]?.[key] || editionMessages['en-US'][key] || dict['zh-CN'][key] || key, [lang])
}
